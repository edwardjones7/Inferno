/**
 * Bundle the live-table rules (src/lib/online/live.ts and the poker and blackjack engines it
 * uses) into one ES module the `table` edge function imports. The edge runtime is Deno, which
 * can't resolve the app's extensionless imports or the "@/..." alias, so the shared code is
 * bundled rather than imported directly. Run after changing any of those files:
 *
 *   npm run edge:build
 *
 * The output is committed so `supabase functions deploy table` works on its own.
 */
import { build } from "esbuild";

await build({
  entryPoints: ["src/lib/online/live.ts"],
  outfile: "supabase/functions/_shared/live.js",
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  legalComments: "none",
  banner: { js: "// Generated by scripts/build-edge.mjs from src/lib/online/live.ts. Do not edit.\n// deno-lint-ignore-file" },
});
console.log("wrote supabase/functions/_shared/live.js");
